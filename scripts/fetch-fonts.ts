/**
 * `npm run fonts:fetch [-- --force]`: self-hosts the Noto font packs used for non-Latin languages
 * (docs/dev/QUESTIONNAIRE_SPEC.md section 6.4). Downloads the OFL-licensed @fontsource-variable packages from the
 * npm registry (no dependency added), keeps only the script slices (Latin/Cyrillic/Vietnamese are covered
 * by Inter), rewrites the @font-face URLs to /fonts/noto/<pack>/, and writes /fonts/noto/<pack>.css.
 * The stylesheet is injected by components/i18n only when a language that needs it is chosen, so
 * unicode-range slices (CJK is ~100) download only for glyphs actually used.
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import type { FontPackId } from "../config/locales";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public/fonts/noto");
const VERSION = "5.3.0";
/** Pack id -> fontsource package and the CSS font-family it defines. */
export const PACKS: Record<FontPackId, { pkg: string; family: string }> = {
  "noto-sc": { pkg: "noto-sans-sc", family: "Noto Sans SC Variable" },
  "noto-tc": { pkg: "noto-sans-tc", family: "Noto Sans TC Variable" },
  "noto-kr": { pkg: "noto-sans-kr", family: "Noto Sans KR Variable" },
  "noto-arabic": { pkg: "noto-sans-arabic", family: "Noto Sans Arabic Variable" },
  "noto-deva": { pkg: "noto-sans-devanagari", family: "Noto Sans Devanagari Variable" },
  "noto-beng": { pkg: "noto-sans-bengali", family: "Noto Sans Bengali Variable" },
  "noto-gujr": { pkg: "noto-sans-gujarati", family: "Noto Sans Gujarati Variable" },
};

/** Keep script slices and numeric CJK slices; drop Latin/Cyrillic/Greek/Vietnamese (Inter covers them). */
export function keepBlock(comment: string): boolean {
  return !/-(latin|latin-ext|cyrillic|cyrillic-ext|greek|greek-ext|vietnamese|math|symbols)-wght/.test(comment);
}

export function rewriteCss(css: string, pack: string): string {
  const blocks = css.split(/(?=\/\* [^*]+ \*\/\s*@font-face)/).filter((b) => b.includes("@font-face"));
  return (
    blocks
      .filter((b) => keepBlock(b.split("\n")[0] ?? ""))
      .map((b) => b.replace(/url\(\.\/files\/([^)]+)\)/g, `url(/fonts/noto/${pack}/$1)`).replace(/font-display:\s*swap/, "font-display: swap"))
      .join("\n") + "\n"
  );
}

async function fetchPack(id: FontPackId) {
  const { pkg } = PACKS[id];
  const tmp = mkdtempSync(path.join(os.tmpdir(), "tb-font-"));
  try {
    const url = `https://registry.npmjs.org/@fontsource-variable/${pkg}/-/${pkg}-${VERSION}.tgz`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const tgz = path.join(tmp, "pack.tgz");
    writeFileSync(tgz, Buffer.from(await res.arrayBuffer()));
    execFileSync("tar", ["xzf", tgz, "-C", tmp]);
    const src = path.join(tmp, "package");
    const css = rewriteCss(readFileSync(path.join(src, "wght.css"), "utf8"), id);
    const files = new Set([...css.matchAll(/\/fonts\/noto\/[^/]+\/([^)]+)\)/g)].map((m) => m[1]!));
    mkdirSync(path.join(OUT, id), { recursive: true });
    for (const f of files) copyFileSync(path.join(src, "files", f), path.join(OUT, id, f));
    writeFileSync(path.join(OUT, `${id}.css`), `/* ${PACKS[id].family}, SIL OFL 1.1. Generated by scripts/fetch-fonts.ts */\n${css}`);
    if (!existsSync(path.join(OUT, "LICENSE"))) copyFileSync(path.join(src, "LICENSE"), path.join(OUT, "LICENSE"));
    const bytes = [...files].reduce((n, f) => n + statSync(path.join(OUT, id, f)).size, 0);
    console.log(`${id}: ${files.size} files, ${(bytes / 1024).toFixed(0)} KB total, largest ${(Math.max(...[...files].map((f) => statSync(path.join(OUT, id, f)).size)) / 1024).toFixed(0)} KB`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

async function main() {
  const force = process.argv.includes("--force");
  mkdirSync(OUT, { recursive: true });
  for (const id of Object.keys(PACKS) as FontPackId[]) {
    if (!force && existsSync(path.join(OUT, `${id}.css`)) && readdirSync(path.join(OUT, id)).length > 0) continue;
    await fetchPack(id);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
