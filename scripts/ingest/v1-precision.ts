/**
 * Precision of the legacy rule-fact keys (prior_*, metastatic, newly_diagnosed, previously_treated, pregnancy,
 * concurrent_trial), which used to penalize unconditionally (fact-policy V1_KEYS). The first hand sample (eval/facts-labels.json,
 * 50 items) found 66% overall and 0/4 for prior_surgery.
 *
 *   npx tsx scripts/ingest/v1-precision.ts --sample [--n=10] [--seed=7]   (writes eval/facts-labels-v3.json, correct: null)
 *   npx tsx scripts/ingest/v1-precision.ts --measure                    (writes config/questionnaire/precision-v1.generated.ts)
 *
 * The sample is drawn once, with a fixed seed, from the held-out partition (lib/ingest/precision.ts partitionOf),
 * minus every trial of the v1 sample, using the current rule layer. Labels are provisional judgments of the quoted
 * criterion (not clinician-reviewed). A key keeps penalizing at >= 85% precision on its labeled items.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { loadCards } from "./cards";
import { partitionOf, PRECISION_GATE } from "../../lib/ingest/precision";
import type { Fact } from "../../lib/types/trial";

export const V1_GATED_KEYS = ["prior_chemotherapy", "prior_radiation", "prior_surgery", "prior_immunotherapy", "prior_targeted_therapy", "metastatic", "newly_diagnosed", "previously_treated", "pregnancy", "concurrent_trial"] as const;
const LABELS = "eval/facts-labels-v3.json";
const GENERATED = "config/questionnaire/precision-v1.generated.ts";

interface V1Label {
  id: string;
  key: string;
  value: string;
  param?: string | number;
  ref: string;
  quote: string;
  correct: boolean | null;
  why?: string;
}

const args = new Map(process.argv.slice(2).map((a) => a.replace(/^--/, "").split("=") as [string, string | undefined]));
const refOf = (f: Fact) => `${f.ref.section === "inclusion" ? "I" : "E"}${f.ref.n}`;

function sample(): void {
  if (existsSync(LABELS)) throw new Error(`${LABELS} exists: the held-out sample is drawn once`);
  const n = Number(args.get("n") ?? 10);
  let seed = Number(args.get("seed") ?? 7);
  const rand = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
  const seen = new Set((JSON.parse(readFileSync("eval/facts-labels.json", "utf8")) as { items: { id: string }[] }).items.map((x) => x.id));
  const cards = loadCards("national").filter((c) => partitionOf(c.id) === "held" && !seen.has(c.id));
  cards.sort((a, b) => a.id.localeCompare(b.id));
  const items: V1Label[] = [];
  for (const key of V1_GATED_KEYS) {
    const pool = cards.flatMap((c) => c.facts.filter((f) => f.key === key && f.value !== "mentioned" && !f.needsReview && typeof f.param !== "string").map((f) => ({ c, f })));
    const used = new Set<string>();
    while (items.filter((x) => x.key === key).length < n && pool.length) {
      const { c, f } = pool.splice(Math.floor(rand() * pool.length), 1)[0]!;
      if (used.has(c.id)) continue; // one fact per trial and key
      used.add(c.id);
      items.push({ id: c.id, key, value: f.value, ...(f.param !== undefined ? { param: f.param } : {}), ref: refOf(f), quote: f.quote, correct: null });
    }
  }
  writeFileSync(LABELS, `${JSON.stringify({ note: "v7 held-out sample of v1 rule facts (rules version 5). correct = the fact (key and direction) is a reasonable reading of the quoted criterion for a patient answering the matching question. provisional labels, not clinician-reviewed.", items }, null, 1)}\n`);
  console.log(`wrote ${items.length} items to ${LABELS}`);
}

function measure(): void {
  const { items } = JSON.parse(readFileSync(LABELS, "utf8")) as { items: V1Label[] };
  const out: Record<string, { labeled: number; correct: number; precision: number; passes: boolean }> = {};
  for (const key of V1_GATED_KEYS) {
    const done = items.filter((x) => x.key === key && x.correct !== null);
    const correct = done.filter((x) => x.correct).length;
    const precision = done.length ? correct / done.length : 0;
    out[key] = { labeled: done.length, correct, precision: Math.round(precision * 1000) / 1000, passes: done.length > 0 && precision >= PRECISION_GATE };
  }
  const body = `/** GENERATED by \`npx tsx scripts/ingest/v1-precision.ts --measure\` from ${LABELS}. Do not edit. */\nexport const V1_KEY_PRECISION: Readonly<Record<string, { labeled: number; correct: number; precision: number; passes: boolean }>> = ${JSON.stringify(out, null, 2)};\n`;
  writeFileSync(GENERATED, body);
  for (const [k, v] of Object.entries(out)) console.log(`${k.padEnd(24)} ${v.correct}/${v.labeled} ${(100 * v.precision).toFixed(0)}% ${v.passes ? "penalizes" : "support-only"}`);
}

if (args.has("sample")) sample();
else if (args.has("measure")) measure();
else console.log("usage: --sample | --measure");
